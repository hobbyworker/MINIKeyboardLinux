//! The descriptors a 1189:8890 reports. Interfaces 0, 2 and 3 are its keyboard, keyboard + consumer and
//! mouse; interface 1, where settings are written, is HID class with only an interrupt OUT endpoint.

use datalayer::descriptors::{self, Endpoint, OutputReport};
use domain::UsagePair;

const CONFIGURATION: [u8; 109] = [
    0x09, 0x02, 0x6D, 0x00, 0x04, 0x01, 0x00, 0xA0, 0x32, 0x09, 0x04, 0x00, 0x00, 0x01, 0x03, 0x01, 0x01, 0x00, 0x09,
    0x21, 0x11, 0x01, 0x00, 0x01, 0x22, 0x40, 0x00, 0x07, 0x05, 0x81, 0x03, 0x40, 0x00, 0x0A, 0x09, 0x04, 0x01, 0x00,
    0x01, 0x03, 0x00, 0x00, 0x00, 0x09, 0x21, 0x00, 0x01, 0x00, 0x01, 0x22, 0x24, 0x00, 0x07, 0x05, 0x02, 0x03, 0x40,
    0x00, 0x0A, 0x09, 0x04, 0x02, 0x00, 0x01, 0x03, 0x00, 0x00, 0x00, 0x09, 0x21, 0x00, 0x01, 0x00, 0x01, 0x22, 0x56,
    0x00, 0x07, 0x05, 0x83, 0x03, 0x04, 0x00, 0x0A, 0x09, 0x04, 0x03, 0x00, 0x01, 0x03, 0x01, 0x02, 0x00, 0x09, 0x21,
    0x10, 0x01, 0x00, 0x01, 0x22, 0x34, 0x00, 0x07, 0x05, 0x82, 0x03, 0x04, 0x00, 0x0A,
];

/// Interface 1: vendor page 0xFF00, report ID 3 with 64 bytes in and 64 bytes out.
const CONFIGURATION_REPORT: [u8; 36] = [
    0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x03, 0x09, 0x02, 0x15, 0x00, 0x26, 0x00, 0xFF, 0x75, 0x08, 0x95,
    0x40, 0x81, 0x06, 0x09, 0x02, 0x15, 0x00, 0x26, 0x00, 0xFF, 0x75, 0x08, 0x95, 0x40, 0x91, 0x06, 0xC0,
];

const MOUSE: [u8; 13] = [0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x75, 0x08, 0x95, 0x04, 0x81, 0x06, 0xC0];

#[test]
fn configuration_interface_has_only_an_out_endpoint() {
    let interface = descriptors::interface(1, &CONFIGURATION).unwrap();
    assert_eq!(interface.out_endpoint(), Some(Endpoint { address: 0x02, max_packet_size: 64 }));
    assert_eq!(interface.report_descriptor_length, Some(36));
}

#[test]
fn input_interfaces_have_no_out_endpoint() {
    for number in [0, 2, 3] {
        assert_eq!(descriptors::interface(number, &CONFIGURATION).unwrap().out_endpoint(), None);
    }
    assert_eq!(descriptors::interface(4, &CONFIGURATION), None);
}

#[test]
fn output_report_is_id_3_with_64_bytes() {
    assert_eq!(descriptors::first_output_report(&CONFIGURATION_REPORT), Some(OutputReport { id: 3, length: 64 }));
}

/// The configuration interface is told from the others by its vendor-defined page.
#[test]
fn configuration_report_is_vendor_defined() {
    assert_eq!(descriptors::usage_page(&CONFIGURATION_REPORT), Some(0xFF00));
    assert_eq!(descriptors::usage_page(&MOUSE), Some(0x01));
    assert_eq!(descriptors::usage_page(&[]), None);
}

/// Firmware without report IDs: the output report is unnumbered.
#[test]
fn unnumbered_output_report_is_id_0() {
    let report = [0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x75, 0x08, 0x95, 0x08, 0x91, 0x02, 0xC0];
    assert_eq!(descriptors::first_output_report(&report), Some(OutputReport { id: 0, length: 8 }));
}

#[test]
fn input_only_descriptor_has_no_output_report() {
    assert_eq!(descriptors::first_output_report(&MOUSE), None);
}

/// What an interface is for: the usage of each top-level collection.
#[test]
fn top_level_usages() {
    assert_eq!(descriptors::top_level_usages(&MOUSE), vec![UsagePair { page: 0x01, usage: 0x02 }]);
    assert_eq!(descriptors::top_level_usages(&CONFIGURATION_REPORT), vec![UsagePair { page: 0xFF00, usage: 0x01 }]);
    // A keyboard and a consumer collection, one after the other, each with a nested collection.
    let both = [
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0xC0, 0xC0, 0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01,
        0xC0,
    ];
    assert_eq!(
        descriptors::top_level_usages(&both),
        vec![UsagePair { page: 0x01, usage: 0x06 }, UsagePair { page: 0x0C, usage: 0x01 }]
    );
}
